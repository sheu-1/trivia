/**
 * Filter questions by theme, category, or custom pool
 */
export function getQuestionsForTheme(
  themeFilter: string,
  customQuestions?: Question[]
): Question[] {
  if (themeFilter === 'custom' && customQuestions && customQuestions.length > 0) {
    return customQuestions;
  }

  // "all" or "general" returns full mix of questions for the "Anything Goes" experience
  if (themeFilter === 'all') {
    return QUESTIONS;
  }

  // Specific category or showdown match
  const matched = QUESTIONS.filter((q) => {
    // Exact battle theme match
    if (q.battleTheme === themeFilter) return true;

    // Exact category match (case-insensitive)
    if (q.category.toLowerCase() === themeFilter.toLowerCase()) return true;

    return false;
  });

  // If specific pool has at least 4 questions, return it; otherwise blend in general questions
  if (matched.length >= 4) {
    return matched;
  }

  return QUESTIONS;
}
